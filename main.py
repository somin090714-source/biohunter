@st.cache_data(ttl=86400, show_spinner=False)
def get_creature_image(name):
    headers = {"User-Agent": "BioHunterEducationalApp/1.0"}
    try:
        url = (
            "https://ko.wikipedia.org/api/rest_v1/page/summary/"
            + quote(name.replace(" ", "_"), safe="")
        )
        response = requests.get(url, headers=headers, timeout=4)
        if response.status_code == 200:
            data = response.json()
            image = (
                data.get("thumbnail", {}).get("source")
                or data.get("originalimage", {}).get("source")
            )
            if image:
                return image
    except (requests.RequestException, ValueError):
        pass

    try:
        response = requests.get(
            "https://commons.wikimedia.org/w/api.php",
            params={
                "action": "query",
                "generator": "search",
                "gsrsearch": f'filetype:bitmap "{name}"',
                "gsrnamespace": 6,
                "gsrlimit": 5,
                "prop": "imageinfo",
                "iiprop": "url|mime",
                "iiurlwidth": 600,
                "format": "json",
            },
            headers=headers,
            timeout=5,
        )
        if response.status_code == 200:
            pages = response.json().get("query", {}).get("pages", {})
            for page in pages.values():
                info = page.get("imageinfo", [{}])[0]
                if info.get("mime", "").startswith("image/"):
                    return info.get("thumburl") or info.get("url")
    except (requests.RequestException, ValueError, IndexError):
        pass
    return None

