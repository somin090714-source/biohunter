def get_terrain_species(terrain):
    allowed = TERRAINS[terrain]["habitats"]
    return [
        s for s in SPECIES
        if any(h in allowed for h in s["habitat"])
    ]

def choose_rarity():
    rarities = list(RARITY_INFO)
    weights = [RARITY_INFO[r]["weight"] for r in rarities]
    return random.choices(rarities, weights=weights, k=1)[0]

def choose_creature(terrain):
    candidates = get_terrain_species(terrain)
    if not candidates:
        candidates = SPECIES

    desired = choose_rarity()
    matching = [s for s in candidates if s["rarity"] == desired]

    if not matching:
        available = list({s["rarity"] for s in candidates})
        desired = random.choice(available)
        matching = [s for s in candidates if s["rarity"] == desired]

    # 중복 생물의 출현 가능성을 조금 높인다.
    weights = [
        1.35 if s["name"] in st.session_state.discovered else 1.0
        for s in matching
    ]
    return random.choices(matching, weights=weights, k=1)[0]

def choose_question(rarity):
    bank = QUIZZES.get(rarity, QUIZZES["일반"])
    used = st.session_state.used_questions.setdefault(rarity, [])
    available = [q for q in bank if q["id"] not in used]

    # 해당 희귀도의 문제를 모두 사용한 경우에만 출제 기록을 초기화한다.
    if not available:
        st.session_state.used_questions[rarity] = []
        available = bank[:]

    question = random.choice(available)
    st.session_state.used_questions[rarity].append(question["id"])

    # 정답 위치를 무작위로 바꾸되 정답은 정확히 따라간다.
    indexed = list(enumerate(question["options"]))
    random.shuffle(indexed)
    new_answer = next(
        i for i, (original_index, _) in enumerate(indexed)
        if original_index == question["answer"]
    )

    return {
        **question,
        "options": [option for _, option in indexed],
        "answer": new_answer,
    }

def start_exploration():
    creature = choose_creature(st.session_state.terrain)
    question = choose_question(creature["rarity"])

    st.session_state.current_creature = creature
    st.session_state.current_question = question
    st.session_state.quiz_answer = None
    st.session_state.quiz_submitted = False
    st.session_state.last_result = None
    st.session_state.encounter_id += 1
    st.session_state.total_encounters += 1

def resolve_answer(selected):
    creature = st.session_state.current_creature
    question = st.session_state.current_question
    if creature is None or question is None or selected is None:
        st.warning("먼저 답을 선택해 줘.")
        return

    st.session_state.quiz_submitted = True
    st.session_state.quiz_answer = selected

    if selected == question["answer"]:
        name = creature["name"]
        rarity = creature["rarity"]
        st.session_state.xp += RARITY_INFO[rarity]["xp"]

        if name in st.session_state.discovered:
            st.session_state.discovered[name]["count"] += 1
            st.session_state.xp += 3
            st.session_state.last_result = "duplicate"
        else:
            st.session_state.discovered[name] = {
                "count": 1,
                "first_terrain": st.session_state.terrain,
            }
            st.session_state.total_found += 1
            st.session_state.last_result = "new"
    else:
        st.session_state.total_missed += 1
        st.session_state.last_result = "missed"

